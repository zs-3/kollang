"""``kol.lock``: the exact resolved package set, for reproducible builds.

Because Kol permits one version per package name, a dependency is recorded by
name alone.  The file is deterministic (sorted, fixed formatting) so it diffs
cleanly in version control and is only rewritten when its content changes.
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field
from typing import Dict, List, Optional

from . import LOCKFILE_VERSION, tomlio
from .errors import KitError
from .semver import Version, VersionError

LOCK_NAME = "kol.lock"

HEADER = (
    "# This file is generated by Kit. Do not edit it by hand.\n"
    "# It pins the exact packages used, so builds are reproducible.\n"
)


@dataclass
class LockedPackage:
    name: str
    version: Version
    source: str = ""                 # "" (root) | "registry+<name>" | "path+<relative path>"
    checksum: str = ""               # "sha256:<hex>" for registry packages
    deps: List[str] = field(default_factory=list)


@dataclass
class Lockfile:
    packages: Dict[str, LockedPackage] = field(default_factory=dict)

    def versions(self) -> Dict[str, Version]:
        return {n: p.version for n, p in self.packages.items() if p.source}

    def archive_checksums(self) -> Dict[str, str]:
        """sha256 hex of every package that came from a url/archive source."""
        out = {}
        for n, p in self.packages.items():
            if p.source.startswith(("url+", "archive+")) and p.checksum.startswith("sha256:"):
                out[n] = p.checksum.split(":", 1)[1]
        return out

    def dumps(self) -> str:
        out = [HEADER, f"version = {LOCKFILE_VERSION}", ""]
        for name in sorted(self.packages):
            p = self.packages[name]
            out.append("[[package]]")
            out.append(f"name = {tomlio.quote(p.name)}")
            out.append(f"version = {tomlio.quote(str(p.version))}")
            if p.source:
                out.append(f"source = {tomlio.quote(p.source)}")
            if p.checksum:
                out.append(f"checksum = {tomlio.quote(p.checksum)}")
            if p.deps:
                out.append("dependencies = [")
                for d in sorted(p.deps):
                    out.append(f"    {tomlio.quote(d)},")
                out.append("]")
            out.append("")
        return "\n".join(out).rstrip("\n") + "\n"

    @classmethod
    def loads(cls, text: str, origin: str = LOCK_NAME) -> "Lockfile":
        try:
            data = tomlio.loads(text)
        except tomlio.TomlError as e:
            raise KitError(f"{origin}: invalid TOML: {e}",
                           hint=f"delete {LOCK_NAME} and run `kit install` to regenerate it")
        fmt = data.get("version", 1)
        if not isinstance(fmt, int) or fmt > LOCKFILE_VERSION:
            raise KitError(f"{origin}: lockfile format {fmt} is newer than this Kit supports "
                           f"({LOCKFILE_VERSION})", hint="upgrade Kit")
        lock = cls()
        for raw in data.get("package", []):
            try:
                pkg = LockedPackage(
                    name=raw["name"],
                    version=Version.parse(raw["version"]),
                    source=raw.get("source", ""),
                    checksum=raw.get("checksum", ""),
                    deps=list(raw.get("dependencies", [])),
                )
            except (KeyError, VersionError, TypeError) as e:
                raise KitError(f"{origin}: malformed [[package]] entry: {e}",
                               hint=f"delete {LOCK_NAME} and run `kit install` to regenerate it")
            lock.packages[pkg.name] = pkg
        return lock

    @classmethod
    def load(cls, path: str) -> Optional["Lockfile"]:
        if not os.path.isfile(path):
            return None
        with open(path, "r", encoding="utf-8") as f:
            return cls.loads(f.read(), origin=path)


def from_resolution(root_name: str, root_version: Version, root_deps: List[str],
                    nodes: Dict[str, "object"], project_root: str) -> Lockfile:
    """Build a Lockfile from a Resolution's nodes."""
    lock = Lockfile()
    lock.packages[root_name] = LockedPackage(root_name, root_version, "", "", sorted(root_deps))
    for name, node in nodes.items():
        if node.source == "path":
            rel = os.path.relpath(node.path, project_root).replace(os.sep, "/")
            source = f"path+{rel}"
            checksum = ""
        elif node.source == "archive":
            if node.origin.lower().startswith(("http://", "https://")):
                source = f"url+{node.origin}"
            else:
                source = "archive+" + os.path.relpath(node.origin, project_root).replace(os.sep, "/")
            checksum = f"sha256:{node.checksum}"
        else:
            source = f"registry+{node.registry}"
            checksum = f"sha256:{node.checksum}" if node.checksum else ""
        lock.packages[name] = LockedPackage(name, node.version, source, checksum, sorted(node.deps))
    return lock
